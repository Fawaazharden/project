import fs from 'fs';

// Same project as src/lib/sanity.ts — personalized landing pages live here.
// Queried over plain HTTP so this script has no node_modules dependency and
// can never break the build by failing to resolve a package.
const PROJECT_ID = 'phcyc64u';
const DATASET = 'production';
const API_VERSION = '2023-05-03';

const OUT = 'public/_redirects';

// Single-segment SPA routes that are not personalized pages.
const SPA_ROUTES = ['/admin'];

async function getPersonalizedSlugs() {
  const query = `*[_type == "personalizedPage" && defined(slug.current)].slug.current`;
  const url =
    `https://${PROJECT_ID}.apicdn.sanity.io/v${API_VERSION}/data/query/${DATASET}` +
    `?query=${encodeURIComponent(query)}`;

  const response = await fetch(url);
  if (!response.ok) {
    throw new Error(`Sanity responded ${response.status} ${response.statusText}`);
  }

  const { result } = await response.json();
  if (!Array.isArray(result)) {
    throw new Error('Unexpected Sanity response shape');
  }

  // Only plain slugs are safe to turn into redirect rules.
  return [...new Set(result)]
    .filter((slug) => typeof slug === 'string' && /^[a-z0-9][a-z0-9-]*$/i.test(slug))
    .sort();
}

function buildRedirects(slugs) {
  const spaRules = [
    ...SPA_ROUTES.flatMap((route) => [
      `${route.padEnd(28)} /index.html                          200`,
      `${(route + '/*').padEnd(28)} /index.html                          200`,
    ]),
    ...slugs.flatMap((slug) => [
      `/${slug}`.padEnd(28) + ' /index.html                          200',
      `/${slug}/`.padEnd(28) + ' /index.html                          200',
    ]),
  ].join('\n');

  return `# GENERATED BY generate-redirects.mjs — do not edit by hand.
# Run \`npm run redirects\` (or just \`npm run build\`) to regenerate.
#
# Rule order matters: Netlify evaluates top to bottom, first match wins.
# Rules without \`!\` never shadow a real file in the publish directory, so
# every static page under public/ keeps serving normally.

# ── Homepage ────────────────────────────────────────────────────────────────
# The live homepage is the Follow Up Boss AI page. It ships as home.html, not
# index.html, because vite emits dist/index.html from the React entry and a
# public/index.html would collide with it. Forced, so the SPA shell cannot win.
/                            /home.html                           200!

# Neither shell nor source file is a page anyone should land on, and both are
# real files in the publish directory, so both need the force.
/home.html                   /                                    301!
/index.html                  /                                    301!

# ── Retired pages, consolidated into the new homepage ───────────────────────
# The AI Acquisition Manager page and the old /fub/ landing page were both
# replaced by the homepage above. Their URLs are indexed, so they redirect
# rather than 404.
#
# public/ai-acquisition-manager/img/ deliberately still exists: every blog post
# points its og:image at /ai-acquisition-manager/img/og/<slug>.png, so deleting
# that directory would break 21 social cards. These rules are unforced, which
# means they never shadow a real file, so the images keep serving and only the
# retired HTML redirects. Do not add \`!\` to either rule.
/ai-acquisition-manager      /                                    301
/ai-acquisition-manager/*    /                                    301
/fub                         /                                    301
/fub/*                       /                                    301

# ── Static landing pages ────────────────────────────────────────────────────
/resimpli                    /resimpli/index.html                 200
/resimpli/                   /resimpli/index.html                 200

# ── Legacy URL consolidation ────────────────────────────────────────────────
# /contact is now a real page, so the old /contact-us URL folds into it.
/contact-us                  /contact/                            301
/contact-us/*                /contact/                            301
/privacy-policy              /privacy/                            301

# Removed blog posts (deleted from Sanity): redirect stale/indexed URLs to the
# blog index rather than the generic catch-all below.
/blog/ai-content-systems-aws-lambda-sanity                                      /blog   301
/blog/the-future-of-ai-powered-content-marketing                                /blog   301
/blog/the-future-of-web-development-ai-powered-tools-transforming-the-industry  /blog   301
/blog/test-blog-post-mcp                                                        /blog   301
/blog/ai-powered-content-marketing-revolution                                   /blog   301
/blog/voice-technology-trends-shaping-indias-future-a-business-guide            /blog   301
/blog/voice-technology-trends-in-india-shaping-the-future-of-communication      /blog   301

# ── Single Page Application routes ──────────────────────────────────────────
# Only these paths are allowed to boot the React bundle. Everything else falls
# through to the catch-all, so a mistyped URL can never render the old site.
${spaRules}

# ── Catch-all ───────────────────────────────────────────────────────────────
# Deliberately none. A same-domain "/*  /  301" does not work: "/" matches
# "/*", so Netlify reads the rule as a redirect loop and silently drops it.
# Unmatched paths fall through to public/404.html, which forwards to the live
# homepage. That is what stops typos like https://vocalxlabs.com/) from
# rendering the retired Vocalx page.
`;
}

async function main() {
  let slugs;
  try {
    slugs = await getPersonalizedSlugs();
  } catch (error) {
    console.error('[redirects] Sanity fetch failed:', error.message);
    console.error(`[redirects] Keeping existing ${OUT} unchanged.`);
    return;
  }

  // A zero-length result is far more likely to be an API hiccup than a real
  // deletion of every personalized page. Never let it silently unpublish them.
  if (!slugs.length) {
    console.error('[redirects] Sanity returned no personalized pages.');
    console.error(`[redirects] Keeping existing ${OUT} unchanged.`);
    return;
  }

  fs.writeFileSync(OUT, buildRedirects(slugs));
  console.log(`[redirects] Wrote ${OUT} with ${slugs.length} personalized pages.`);
}

main();
